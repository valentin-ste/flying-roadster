#!/usr/bin/env python3
"""Menu bar icon of the Roadster app: three variants as template SVGs (black + alpha; macOS tints them).

The shape comes from our render: the car's silhouette on show B frame 600 (it stands on the floor, side on,
facing right), cropped to mask-0600-crop.png. The body is that silhouette without the wheels' bumps,
smoothed and simplified; the wheels are circles at the measured centres. At menu bar size the real
proportions (3.9 : 1) give a car 7.7 pt tall that reads as a thin strip, so the body is drawn taller (--k)
and the wheels bigger (--kw) than on the render.

  .venv/bin/python3 design/icon/make_icons.py            # -> design/icon/roadster-{solid,wheels,outline}.svg
  .venv/bin/python3 design/icon/make_icons.py --k 1 --kw 1 --suffix -true   # the true proportions
PNG @1x/@2x of each: design/shoot.py icons.
"""
import argparse
import pathlib

import numpy as np
from PIL import Image
from scipy.ndimage import gaussian_filter

HERE = pathlib.Path(__file__).resolve().parent
SRC = HERE / "mask-0600-crop.png"     # out/show-b/final-cloud/clip-mask/0600.png, crop (1190, 1724, 2112, 1964)

FLOOR = 240                           # the floor line in the crop (its bottom edge)
WHEELS = (175, 748)                   # wheel centres, x in the crop: middles of the floor contacts
R_WHEEL = 68                          # wheel radius in crop px, fitted to the bumps below the body
SILL = 213                            # the body's lower edge between the wheels


def body_outline(sigma, tol):
    """The body as a closed polygon in crop px: the silhouette cut at the sill, smoothed, simplified."""
    m = np.array(Image.open(SRC)) > 127
    m[SILL:, :] = False                                   # no wheel bumps, no lip under the bumpers
    pad = 24
    m = np.pad(m, pad)
    s = gaussian_filter(m.astype(float), sigma) > 0.5
    cols = np.nonzero(s.any(0))[0]
    top, bot = [], []
    for x in cols:
        ys = np.nonzero(s[:, x])[0]
        top.append((x - pad, ys[0] - pad))
        bot.append((x - pad, ys[-1] + 1 - pad))
    pts = top + bot[::-1]
    return dp(np.array(pts, float), tol)


def dp(pts, tol):
    """Douglas-Peucker on a closed polygon (split at the two ends of the longest chord)."""
    def rec(p):
        if len(p) < 3:
            return list(p)
        a, b = p[0], p[-1]
        d = b - a
        n = np.hypot(*d) or 1.0
        dist = np.abs(d[0] * (p[:, 1] - a[1]) - d[1] * (p[:, 0] - a[0])) / n
        i = int(np.argmax(dist))
        if dist[i] <= tol:
            return [a, b]
        return rec(p[: i + 1])[:-1] + rec(p[i:])
    i_far = int(np.argmax(pts[:, 0]))
    return np.array(rec(pts[: i_far + 1])[:-1] + rec(np.vstack([pts[i_far:], pts[:1]]))[:-1])


def to_icon(pts, k, scale, ox, floor_y):
    out = pts.astype(float).copy()
    out[:, 0] = ox + out[:, 0] * scale
    out[:, 1] = floor_y - (FLOOR - out[:, 1]) * k * scale
    return out


def path_d(pts):
    return "M" + " L".join(f"{x:.2f} {y:.2f}" for x, y in pts) + " Z"


def svg(variant, body, wheels, r, gap, stroke, w, h):
    d = path_d(body)
    head = (f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" viewBox="0 0 {w} {h}">\n'
            f'<!-- Roadster menu bar icon, variant "{variant}": a template image (black + alpha), '
            f'macOS draws it white or dark. Generated by design/icon/make_icons.py. -->\n')
    arches = "".join(f'<circle cx="{cx:.2f}" cy="{cy:.2f}" r="{r + gap:.2f}" fill="#000"/>' for cx, cy in wheels)
    if variant == "solid":
        discs = "".join(f'<circle cx="{cx:.2f}" cy="{cy:.2f}" r="{r:.2f}"/>' for cx, cy in wheels)
        return head + f'<g fill="#000"><path d="{d}"/>{discs}</g>\n</svg>\n'
    if variant == "wheels":
        discs = "".join(f'<circle cx="{cx:.2f}" cy="{cy:.2f}" r="{r:.2f}"/>' for cx, cy in wheels)
        return head + (
            f'<defs><mask id="arch" maskUnits="userSpaceOnUse" x="0" y="0" width="{w}" height="{h}">'
            f'<rect width="{w}" height="{h}" fill="#fff"/>{arches}</mask></defs>\n'
            f'<path d="{d}" fill="#000" mask="url(#arch)"/>\n<g fill="#000">{discs}</g>\n</svg>\n')
    # outline: the edge of (body minus the arches) and the wheels as rings
    arch_rings = "".join(f'<circle cx="{cx:.2f}" cy="{cy:.2f}" r="{r + gap:.2f}"/>' for cx, cy in wheels)
    rings = "".join(f'<circle cx="{cx:.2f}" cy="{cy:.2f}" r="{r - stroke / 2:.2f}"/>' for cx, cy in wheels)
    hubs = "".join(f'<circle cx="{cx:.2f}" cy="{cy:.2f}" r="{stroke * 0.55:.2f}"/>' for cx, cy in wheels)
    return head + (
        f'<defs>'
        f'<mask id="out" maskUnits="userSpaceOnUse" x="0" y="0" width="{w}" height="{h}">'
        f'<rect width="{w}" height="{h}" fill="#fff"/>{arches}</mask>'
        f'<clipPath id="in"><path d="{d}"/></clipPath>'
        f'</defs>\n'
        f'<path d="{d}" fill="none" stroke="#000" stroke-width="{stroke}" stroke-linejoin="round" mask="url(#out)"/>\n'
        f'<g fill="none" stroke="#000" stroke-width="{stroke}" clip-path="url(#in)">{arch_rings}</g>\n'
        f'<g fill="none" stroke="#000" stroke-width="{stroke}">{rings}</g>\n'
        f'<g fill="#000">{hubs}</g>\n</svg>\n')


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--w", type=float, default=32, help="canvas width, pt")
    ap.add_argument("--h", type=float, default=18, help="canvas height, pt")
    ap.add_argument("--length", type=float, default=30, help="the car's length on the canvas, pt")
    ap.add_argument("--k", type=float, default=1.35, help="body height x this (1 = as on the render)")
    ap.add_argument("--kw", type=float, default=1.1, help="wheel radius x this")
    ap.add_argument("--gap", type=float, default=0.6, help="gap around a wheel in the 'wheels' and 'outline' variants, pt")
    ap.add_argument("--stroke", type=float, default=1.25, help="line width of the outline variant, pt")
    ap.add_argument("--sigma", type=float, default=7, help="smoothing of the silhouette, crop px")
    ap.add_argument("--tol", type=float, default=0.8, help="simplification tolerance, crop px")
    ap.add_argument("--suffix", default="")
    a = ap.parse_args()

    body = body_outline(a.sigma, a.tol)
    x0, x1 = body[:, 0].min(), body[:, 0].max()
    scale = a.length / (x1 - x0)
    height = (FLOOR - body[:, 1].min()) * a.k * scale
    floor_y = (a.h + height) / 2
    ox = (a.w - a.length) / 2 - x0 * scale
    ib = to_icon(body, a.k, scale, ox, floor_y)
    r = R_WHEEL * a.kw * scale
    wheels = [(ox + cx * scale, floor_y - r) for cx in WHEELS]
    print(f"body {len(body)} points; car {a.length:.1f} x {height:.2f} pt, wheel d {2 * r:.2f} pt, scale {scale:.4f} pt/px")
    for v in ("solid", "wheels", "outline"):
        f = HERE / f"roadster-{v}{a.suffix}.svg"
        f.write_text(svg(v, ib, wheels, r, a.gap, a.stroke, a.w, a.h))
        print(f)
    if not a.suffix:
        app_icon(ib, wheels, r, a.w, a.h)


def app_icon(body, wheels, r, w, h):
    """A placeholder app icon (the alert, About, the panel's header): a graphite tile and the white car."""
    d = path_d(body)
    discs = "".join(f'<circle cx="{cx:.2f}" cy="{cy:.2f}" r="{r:.2f}"/>' for cx, cy in wheels)
    s = 96 / w                                    # the car 90 of 128 wide
    f = HERE / "app-icon-placeholder.svg"
    f.write_text(
        '<svg xmlns="http://www.w3.org/2000/svg" width="128" height="128" viewBox="0 0 128 128">\n'
        '<!-- Placeholder app icon (not designed yet). Generated by design/icon/make_icons.py. -->\n'
        '<defs><linearGradient id="g" x1="0" y1="0" x2="0" y2="1">'
        '<stop offset="0" stop-color="#4A505A"/><stop offset="1" stop-color="#16181C"/></linearGradient>'
        '<radialGradient id="glow" cx="0.5" cy="0.5" r="0.5">'
        '<stop offset="0" stop-color="#fff" stop-opacity="0.35"/><stop offset="1" stop-color="#fff" stop-opacity="0"/>'
        '</radialGradient></defs>\n'
        '<rect x="12" y="12" width="104" height="104" rx="23.5" fill="url(#g)"/>\n'
        '<ellipse cx="64" cy="83" rx="46" ry="7" fill="url(#glow)"/>\n'
        f'<g transform="translate({64 - w / 2 * s:.2f} {83 - (wheels[0][1] + r) * s:.2f}) scale({s:.4f})" fill="#fff">'
        f'<path d="{d}"/>{discs}</g>\n</svg>\n')
    print(f)


if __name__ == "__main__":
    main()
